<?php

declare(strict_types=1);

use Pest\Rector\Rules\ChainExpectCallsRector;
use Pest\Rector\Set\PestSetList;
use Rector\Config\RectorConfig;
use Rector\Php83\Rector\ClassMethod\AddOverrideAttributeToOverriddenMethodsRector;
use Rector\Privatization\Rector\Property\PrivatizeFinalClassPropertyRector;
use Rector\TypeDeclaration\Rector\ClassMethod\StrictArrayParamDimFetchRector;

return RectorConfig::configure()
    ->withPaths([
        __DIR__.'/app',
        __DIR__.'/bootstrap/app.php',
        __DIR__.'/config',
        __DIR__.'/database',
        __DIR__.'/public',
        __DIR__.'/routes',
        __DIR__.'/tests',
    ])
    ->withSkip([
        AddOverrideAttributeToOverriddenMethodsRector::class,

        // `protected bool $hidesDrawer` is the framework's documented bare-property
        // shorthand (nativephp/mobile-ui InteractsWithDrawer). Narrowing it to
        // private only survives because screenHides() reaches it by reflection.
        PrivatizeFinalClassPropertyRector::class,

        // Types `Http::assertSent()` callbacks as `array`. Laravel passes an
        // Illuminate\Http\Client\Request, so the result is a TypeError.
        StrictArrayParamDimFetchRector::class,

        // Merges independent expect() calls into ->and() chains, which collapses
        // assertion granularity and mis-indents the nested arrays it hoists.
        ChainExpectCallsRector::class,

        // Generated icon enums: 12k lines across 3 files, regenerated by the
        // build. Pint already excludes them for the same reason.
        __DIR__.'/app/Icons',
    ])
    ->withPreparedSets(
        deadCode: true,
        codeQuality: true,
        typeDeclarations: true,
        privatization: true,
        earlyReturn: true,
    )
    ->withSets([
        PestSetList::CODING_STYLE,
    ])
    ->withPhpSets();
